// Builds src/renderer/lib/i18n-en.js from the Spanish source strings.
//  - first run: node scripts/i18n/gen.mjs --init  (pairs strings with en.txt by order)
//  - later runs: keeps existing translations and lists missing ones
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const outFile = path.join(root, 'src/renderer/lib/i18n-en.js');

function sources(dir) {
  const files = [];
  (function walk(d) {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (/\.(jsx?|mjs)$/.test(e.name) && !p.includes('i18n-en')) files.push(p);
    }
  })(path.join(root, dir));
  return files;
}

function extract() {
  const set = new Set();
  const collect = (files, re) => {
    for (const f of files) {
      const s = fs.readFileSync(f, 'utf8');
      for (const m of s.matchAll(re)) {
        const text = m[2].replace(/\\(['"`\\])/g, '$1');
        if (text.includes('${')) console.log(`  not translatable (a template literal): ${path.relative(root, f)}: ${text}`);
        else set.add(text);
      }
    }
  };
  // the interface: t('…')
  collect(sources('src/renderer'), /\bt\(\s*(['"`])((?:\\.|(?!\1).)*)\1/g);
  // texts of the main process the interface translates: tr('…') and
  // new UserError('…') (src/shared/usertext.js)
  collect([...sources('src/main'), ...sources('src/shared')], /\b(?:tr|UserError)\(\s*(['"`])((?:\\.|(?!\1).)*)\1/g);
  const theme = fs.readFileSync(path.join(root, 'src/shared/themes.js'), 'utf8');
  for (const m of theme.matchAll(/name: '([^']+)'/g)) set.add(m[1]);
  return [...set].sort();
}

const strings = extract();
let dict = {};
if (process.argv.includes('--init')) {
  const en = fs.readFileSync(path.join(root, 'scripts/i18n/en.txt'), 'utf8').split('\n').filter((l, i, a) => i < a.length - 1 || l);
  if (en.length !== strings.length) {
    console.error(`Line count mismatch: ${strings.length} strings vs ${en.length} translations`);
    process.exit(1);
  }
  strings.forEach((s, i) => (dict[s] = en[i]));
} else if (fs.existsSync(outFile)) {
  const txt = fs.readFileSync(outFile, 'utf8');
  dict = JSON.parse(txt.slice(txt.indexOf('{'), txt.lastIndexOf('}') + 1));
}
const missing = strings.filter((s) => !(s in dict));
// Every translation already there stays, in its order: some are for texts
// this script cannot find (shown through a variable, like the log
// diagnoses), so one it does not see is only listed, never dropped.
const out = process.argv.includes('--init') ? Object.fromEntries(strings.filter((s) => s in dict).map((s) => [s, dict[s]])) : { ...dict };
const found = new Set(strings);
const unseen = Object.keys(out).filter((k) => !found.has(k));
fs.writeFileSync(outFile, `// English translations (Spanish source string -> English). Generated by scripts/i18n/gen.mjs\nexport default ${JSON.stringify(out, null, 1)};\n`);
console.log(`${Object.keys(out).length} translations written, ${missing.length} missing, ${unseen.length} not found in the code (kept)`);
for (const m of missing) console.log('  missing:', m);
// placeholder sanity check
for (const [k, v] of Object.entries(out)) {
  const a = (k.match(/\{\w+\}/g) || []).sort().join();
  const b = (v.match(/\{\w+\}/g) || []).sort().join();
  if (a !== b) console.log('  placeholder mismatch:', k, '=>', v);
}
